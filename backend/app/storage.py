def key_for_source(project_id: str, artifact_id: str, extension: str) -> str:
    ext = extension if extension.startswith(".") else "." + extension
    if not re.match(r"^\.[A-Za-z0-9]{1,8}$", ext):
        raise StorageError("unsupported extension for storage key")
    return safe_key("sources", project_id, f"{artifact_id}{ext.lower()}")


def key_for_model(project_id: str, model_version_id: str) -> str:
    return safe_key("models", project_id, f"{model_version_id}.glb")


def key_for_reference(project_id: str, shot_plan_id: str, shot_id: str, kind: str) -> str:
    safe_shot = re.sub(r"[^A-Za-z0-9_\-]", "_", shot_id)[:64]
    return safe_key("references", project_id, shot_plan_id, f"{safe_shot}_{kind}.png")


def key_for_clip(project_id: str, job_id: str, shot_id: str, attempt: int) -> str:
    safe_shot = re.sub(r"[^A-Za-z0-9_\-]", "_", shot_id)[:64]
    return safe_key("clips", project_id, job_id, f"{safe_shot}_a{attempt}.mp4")


def key_for_video(project_id: str, video_version_id: str) -> str:
    return safe_key("videos", project_id, f"{video_version_id}.mp4")


def key_for_poster(project_id: str, video_version_id: str) -> str:
    return safe_key("posters", project_id, f"{video_version_id}.jpg")
