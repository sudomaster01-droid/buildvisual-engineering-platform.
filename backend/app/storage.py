"""Object storage abstraction.

Two backends behind one interface:

* ``LocalStorage`` — private directory on disk, keys are opaque UUID-ish paths.
  Nothing under it is served by a static file handler; every byte leaves through
  an authenticated endpoint or a short-lived signed link the app itself verifies.
* ``S3Storage`` — any S3-compatible bucket, presigned GETs for delivery.

Keys are generated by the application, never derived from user filenames, so a
path-traversal or double-extension trick cannot escape the prefix.
"""

from __future__ import annotations

import hashlib
import hmac
import os
import re
import shutil
import time
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO

from .config import get_settings

_SAFE_SEGMENT = re.compile(r"^[A-Za-z0-9._\-]{1,128}$")


class StorageError(RuntimeError):
    pass


def safe_key(*segments: str) -> str:
    """Build an object key from validated segments only."""
    parts = []
    for seg in segments:
        if not seg or not _SAFE_SEGMENT.match(seg) or seg in (".", ".."):
            raise StorageError(f"unsafe storage key segment: {seg!r}")
        parts.append(seg)
    return "/".join(parts)


@dataclass(frozen=True)
class StoredObject:
    key: str
    size: int
    checksum: str


class Storage:
    #: Which backend is active, surfaced in diagnostics.
    name: str = "unknown"

    def put_bytes(self, key: str, data: bytes) -> StoredObject: ...
    def put_file(self, key: str, path: Path) -> StoredObject: ...
    def open_reader(self, key: str) -> BinaryIO: ...
    def exists(self, key: str) -> bool: ...
    def size(self, key: str) -> int: ...
    def delete(self, key: str) -> None: ...
    def local_path(self, key: str) -> Path | None:
        """Return a real filesystem path when the backend is local (media tools)."""
        return None


class LocalStorage(Storage):
    name = "local"

    def __init__(self, root: Path | None = None) -> None:
        settings = get_settings()
        self.root = (root or (settings.data_dir / "objects")).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        candidate = (self.root / key).resolve()
        if not str(candidate).startswith(str(self.root)):
            raise StorageError("resolved path escaped the storage root")
        return candidate

    def put_bytes(self, key: str, data: bytes) -> StoredObject:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".part")
        tmp.write_bytes(data)
        os.replace(tmp, path)
        return StoredObject(key, len(data), hashlib.sha256(data).hexdigest())

    def put_file(self, key: str, source: Path) -> StoredObject:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".part")
        shutil.copyfile(source, tmp)
        os.replace(tmp, path)
        return StoredObject(key, path.stat().st_size, sha256_file(path))

    def open_reader(self, key: str) -> BinaryIO:
        path = self._path(key)
        if not path.exists():
            raise StorageError(f"object not found: {key}")
        return path.open("rb")

    def exists(self, key: str) -> bool:
        return self._path(key).exists()

    def size(self, key: str) -> int:
        return self._path(key).stat().st_size

    def delete(self, key: str) -> None:
        path = self._path(key)
        if path.exists():
            path.unlink()

    def local_path(self, key: str) -> Path | None:
        return self._path(key)


class S3Storage(Storage):
    name = "s3"

    def __init__(self) -> None:
        settings = get_settings()
        if not settings.s3_bucket:
            raise StorageError("S3_BUCKET is not configured")
        try:
            import boto3  # imported lazily; optional dependency
        except ImportError as exc:  # pragma: no cover - depends on install extras
            raise StorageError(
                "S3 storage requested but 'boto3' is not installed. "
                "Install with: pip install 'buildvisual[storage]'"
            ) from exc
        self.bucket = settings.s3_bucket
        self.client = boto3.client(
            "s3",
            region_name=settings.s3_region,
            endpoint_url=settings.s3_endpoint_url or None,
            aws_access_key_id=settings.s3_access_key_id or None,
            aws_secret_access_key=settings.s3_secret_access_key or None,
        )

    def put_bytes(self, key: str, data: bytes) -> StoredObject:
        self.client.put_object(Bucket=self.bucket, Key=key, Body=data)
        return StoredObject(key, len(data), hashlib.sha256(data).hexdigest())

    def put_file(self, key: str, source: Path) -> StoredObject:
        checksum = sha256_file(source)
        self.client.upload_file(str(source), self.bucket, key)
        return StoredObject(key, source.stat().st_size, checksum)

    def open_reader(self, key: str) -> BinaryIO:  # pragma: no cover - network
        response = self.client.get_object(Bucket=self.bucket, Key=key)
        return response["Body"]

    def exists(self, key: str) -> bool:  # pragma: no cover - network
        try:
            self.client.head_object(Bucket=self.bucket, Key=key)
            return True
        except Exception:
            return False

    def size(self, key: str) -> int:  # pragma: no cover - network
        return self.client.head_object(Bucket=self.bucket, Key=key)["ContentLength"]

    def delete(self, key: str) -> None:  # pragma: no cover - network
        self.client.delete_object(Bucket=self.bucket, Key=key)

    def presigned_url(self, key: str, expires_seconds: int = 300) -> str:  # pragma: no cover
        return self.client.generate_presigned_url(
            "get_object",
            Params={"Bucket": self.bucket, "Key": key},
            ExpiresIn=expires_seconds,
        )


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


