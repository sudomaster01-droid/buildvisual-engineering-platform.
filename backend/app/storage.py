def sign_download(key: str, *, expires_in: int = 600, scope: str = "file") -> str:
    """Return a short-lived opaque signature: ``<exp>.<nonce>.<hmac>``."""
    settings = get_settings()
    expires = int(time.time()) + expires_in
    nonce = os.urandom(8).hex()
    msg = f"{scope}:{key}:{expires}:{nonce}".encode()
    mac = hmac.new(settings.resolved_secret.encode(), msg, hashlib.sha256).hexdigest()
    return f"{expires}.{nonce}.{mac}"


def verify_download(key: str, token: str, *, scope: str = "file") -> bool:
    settings = get_settings()
    try:
        expires_s, nonce, mac = token.split(".", 2)
        expires = int(expires_s)
    except (ValueError, AttributeError):
        return False
    if expires < int(time.time()):
        return False
    msg = f"{scope}:{key}:{expires}:{nonce}".encode()
    expected = hmac.new(settings.resolved_secret.encode(), msg, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, mac)


def sign_media_token(key: str, *, expires_in: int = 300, scope: str = "video") -> str:
    """Self-contained, signed token: ``<b64url key>.<exp>.<nonce>.<mac>``.

    The storage key is carried inside the token because it is not a secret — the
    HMAC is what authorises the download, and binding the key into the signature
    means a token cannot be replayed against a different object.
    """
    import base64

    settings = get_settings()
    expires = int(time.time()) + max(30, expires_in)
    nonce = os.urandom(8).hex()
    encoded = base64.urlsafe_b64encode(key.encode()).decode().rstrip("=")
    msg = f"{scope}:{key}:{expires}:{nonce}".encode()
    mac = hmac.new(settings.resolved_secret.encode(), msg, hashlib.sha256).hexdigest()
    return f"{encoded}.{expires}.{nonce}.{mac}"


def parse_media_token(token: str, *, scope: str | None = None) -> tuple[str, str] | None:
    """Return ``(key, scope)`` for a valid, unexpired token, else ``None``."""
    import base64

    settings = get_settings()
    try:
        encoded, expires_s, nonce, mac = token.split(".", 3)
        expires = int(expires_s)
        padded = encoded + "=" * (-len(encoded) % 4)
        key = base64.urlsafe_b64decode(padded.encode()).decode()
    except (ValueError, UnicodeDecodeError):
        return None
    if expires < int(time.time()):
        return None
    for candidate_scope in ((scope,) if scope else ("video", "poster", "file")):
        msg = f"{candidate_scope}:{key}:{expires}:{nonce}".encode()
        expected = hmac.new(settings.resolved_secret.encode(), msg, hashlib.sha256).hexdigest()
        if hmac.compare_digest(expected, mac):
            return key, candidate_scope
    return None


_storage: Storage | None = None


def get_storage() -> Storage:
    global _storage
    if _storage is None:
        settings = get_settings()
        _storage = S3Storage() if settings.storage_backend == "s3" else LocalStorage()
    return _storage


def reset_storage() -> None:
    global _storage
    _storage = None


