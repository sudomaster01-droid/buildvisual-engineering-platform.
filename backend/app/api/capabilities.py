"""What this deployment can actually do — the honest capability report (p.28)."""

from __future__ import annotations

from fastapi import APIRouter

from ..config import get_settings
from ..services.interpret.llm import DEFAULT_MODELS, llm_available
from ..services.speech.transcribe import transcription_available
from ..services.video.factory import capability_report, build_provider, is_external
from .deps import CurrentUser
from .schemas import CapabilitiesOut

router = APIRouter(tags=["capabilities"])

_PROVIDER_LABELS = {
    "veo": "Google Veo 3.1",
    "runway": "Runway Gen-4.5",
    "local_render": "Built-in model renderer",
}


@router.get("/capabilities", response_model=CapabilitiesOut)
def capabilities(_user: CurrentUser) -> CapabilitiesOut:
    """Deployment capability report.

    Authenticated on purpose: it reveals which providers and models are
    configured, which is operational information, not public marketing copy.
    """
    settings = get_settings()
    provider_name = settings.resolved_video_provider
    external = is_external(provider_name)
    all_providers = capability_report()
    report = {"declared_limitations": []}
    limitations: list[str] = []

    if not llm_available():
        limitations.append(
            "Reading uploaded drawings needs a vision model; type or speak the "
            "requirements instead."
        )
    if not transcription_available():
        limitations.append("Voice notes need a transcription key; type the requirements instead.")
    if external and not (
        (provider_name == "veo" and settings.gemini_api_key)
        or (provider_name == "runway" and settings.runway_api_key)
    ):
        limitations.append(
            f"The configured provider ({_PROVIDER_LABELS.get(provider_name, provider_name)}) "
            "has no API key in this deployment, so generation will stop with a clear error."
        )
    if all_providers.get("structural_lock_note"):
        limitations.append(all_providers["structural_lock_note"])
    selected = (all_providers.get("available") or {}).get(provider_name) or {}
    if selected.get("available") is False:
        limitations.append(
            f"{_PROVIDER_LABELS.get(provider_name, provider_name)} is not ready: "
            f"{selected.get('reason', 'unavailable')}"
        )
    limitations.append(
        "Provider output is guided by reference frames and prompts; no configured video "
        "model accepts a structural lock, so architectural fidelity is not guaranteed."
    )

    note = (
        f"Scenes are generated by {_PROVIDER_LABELS.get(provider_name, provider_name)}."
        if external
        else "No AI video key is configured, so films are rendered directly from the "
        "locked 3D model (a model render, not AI footage)."
    )
    try:
        provider_display = build_provider(provider_name).capabilities().model
    except Exception:  # pragma: no cover - provider construction is side-effect free
        provider_display = _PROVIDER_LABELS.get(provider_name, provider_name)

    return CapabilitiesOut(
        drawing_interpretation=llm_available(),
        transcription=transcription_available(),
        video_provider=provider_name,
        video_provider_external=external,
        video_provider_display=provider_display,
        video_note=note,
        accepted_drawing_formats=[
            ext.lstrip(".").upper() for ext in settings.allowed_drawing_extensions
        ],
        accepted_audio_formats=[
            ext.lstrip(".").upper() for ext in settings.allowed_audio_extensions
        ],
        max_upload_mb=settings.max_upload_bytes // (1024 * 1024),
        max_audio_seconds=settings.max_audio_seconds,
        max_text_chars=settings.max_text_chars,
        max_shots=settings.max_shots,
        shot_seconds=settings.shot_seconds,
        llm_provider=(
            f"{settings.resolved_llm_provider} ({DEFAULT_MODELS.get(settings.resolved_llm_provider, settings.llm_model) if not settings.llm_model else settings.llm_model})"
            if llm_available() else "none"
        ),
        limitations=limitations,
    )
